// Bundles the sandbox worker bootstrap (packages/loader/src/bootstrap-entry.ts) into a string exported from bootstrap.generated.ts.
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const r = await build({
  entryPoints: [path.join(root, 'packages/loader/src/bootstrap-entry.ts')], bundle: true, format: 'iife', platform: 'browser', target: 'es2022', minify: true, write: false, logLevel: 'warning', legalComments: 'none',
})
const src = r.outputFiles[0].text
writeFileSync(path.join(root, 'packages/loader/src/bootstrap.generated.ts'), `// Generated by scripts/gen-bootstrap.mjs. Do not edit.\nexport const BOOTSTRAP_SOURCE = ${JSON.stringify(src)}\n`)
